#!/usr/bin/env bash
#
# Regenerates Sources/ArmaziCore/Engine/EmbeddedBenchmarks.swift from the YAML
# files in Sources/ArmaziCore/Benchmarks/, so the binary stays self-contained
# without Bundle.module resource lookups.
#
#   ./Scripts/embed-benchmarks.sh           rewrite the Swift file
#   ./Scripts/embed-benchmarks.sh --check   exit non-zero if it is out of date
#
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
benchmarks_dir="$repo_root/Sources/ArmaziCore/Benchmarks"
output="$repo_root/Sources/ArmaziCore/Engine/EmbeddedBenchmarks.swift"

# Swift constant name : YAML file name
entries=(
  "cisMacOS:cis-macos-benchmark.yaml"
  "personalMacOS:personal-macos-benchmark.yaml"
)

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "import Foundation"
  echo
  echo "/// Benchmark YAML files embedded as string literals so the binary is fully"
  echo "/// self-contained and needs no Bundle.module resource loading."
  echo "///"
  echo "/// Generated by Scripts/embed-benchmarks.sh — do not edit by hand."
  echo "/// Re-run that script after changing anything in Sources/ArmaziCore/Benchmarks/."
  echo "enum EmbeddedBenchmarks {"
} > "$tmp"

first=true
for entry in "${entries[@]}"; do
  constant="${entry%%:*}"
  file="$benchmarks_dir/${entry#*:}"

  if [ ! -f "$file" ]; then
    echo "error: missing benchmark file: $file" >&2
    exit 1
  fi

  # The YAML is embedded in a raw string literal delimited by #""" ... """#.
  if grep -q '"""#' "$file"; then
    echo "error: $file contains the raw string terminator (\"\"\"#)" >&2
    exit 1
  fi

  if [ "$first" = true ]; then
    first=false
  else
    echo >> "$tmp"
  fi

  {
    echo "    static let $constant: String = #\"\"\""
    cat "$file"
    echo "\"\"\"#"
  } >> "$tmp"
done

echo "}" >> "$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! diff -q "$output" "$tmp" > /dev/null 2>&1; then
    echo "error: $output is out of date — run ./Scripts/embed-benchmarks.sh" >&2
    diff -u "$output" "$tmp" || true
    exit 1
  fi
  echo "EmbeddedBenchmarks.swift is up to date."
  exit 0
fi

mv "$tmp" "$output"
trap - EXIT
echo "Wrote $output"
