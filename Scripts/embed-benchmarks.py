#!/usr/bin/env python3
"""Regenerate Sources/ArmaziCore/Engine/EmbeddedBenchmarks.swift.

Benchmark YAML files are embedded in the binary as raw string literals so
that `armazi` works with no bundle resources and no network. Keeping the
literals in sync by hand invites drift, so this script is the only writer
of that file.

  Scripts/embed-benchmarks.py            regenerate the Swift file
  Scripts/embed-benchmarks.py --check    fail if it is out of date (CI)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCHMARK_DIR = ROOT / "Sources" / "ArmaziCore" / "Benchmarks"
OUTPUT = ROOT / "Sources" / "ArmaziCore" / "Engine" / "EmbeddedBenchmarks.swift"

# Benchmark file → Swift property name. Adding a benchmark means adding it
# here (and loading it from BenchmarkRegistry).
EMBEDDED = {
    "cis-macos-benchmark.yaml": "cisMacOS",
    "personal-protection-macos.yaml": "personalProtectionMacOS",
}

HEADER = """import Foundation

/// Benchmark YAML files embedded as raw string literals.
/// This avoids the need for Bundle.module resource loading,
/// making the binary fully self-contained.
///
/// Generated by Scripts/embed-benchmarks.py — do not edit by hand.
/// Edit the YAML in Sources/ArmaziCore/Benchmarks/ and re-run the script.
enum EmbeddedBenchmarks {
"""


def render() -> str:
    parts = [HEADER]
    for index, (filename, property_name) in enumerate(EMBEDDED.items()):
        path = BENCHMARK_DIR / filename
        if not path.exists():
            sys.exit(f"error: {path} does not exist")

        content = path.read_text().rstrip("\n")
        if '"""#' in content:
            sys.exit(f"error: {filename} contains a raw string terminator")

        if index > 0:
            parts.append("\n")
        parts.append(f'    static let {property_name}: String = #"""\n')
        parts.append(content)
        parts.append('\n"""#\n')
    parts.append("}\n")
    return "".join(parts)


def main() -> int:
    generated = render()
    check_only = "--check" in sys.argv

    if check_only:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != generated:
            print(
                "EmbeddedBenchmarks.swift is out of date with the benchmark YAML.\n"
                "Run: Scripts/embed-benchmarks.py"
            )
            return 1
        print(f"EmbeddedBenchmarks.swift is up to date ({len(EMBEDDED)} benchmarks).")
        return 0

    OUTPUT.write_text(generated)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(EMBEDDED)} benchmarks).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
