#!/usr/bin/env python3
"""Regenerate Sources/ArmaziCore/Engine/EmbeddedBenchmarks.swift from the source YAML.

The bundled benchmark is embedded in the binary as a Swift raw string literal so
that `armazi` stays self-contained. That copy must never drift from the YAML in
Sources/ArmaziCore/Benchmarks/.

    python3 Scripts/embed_benchmarks.py            # regenerate the Swift file
    python3 Scripts/embed_benchmarks.py --check    # fail if it is out of date

Uses only the standard library so it can run anywhere, including CI.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
YAML = ROOT / "Sources/ArmaziCore/Benchmarks/cis-macos-benchmark.yaml"
SWIFT = ROOT / "Sources/ArmaziCore/Engine/EmbeddedBenchmarks.swift"

HEADER = '''import Foundation

/// Bundled CIS macOS Benchmark embedded as a string literal.
/// This avoids the need for Bundle.module resource loading,
/// making the binary fully self-contained.
///
/// Generated by Scripts/embed_benchmarks.py — do not edit by hand.
/// Edit Sources/ArmaziCore/Benchmarks/cis-macos-benchmark.yaml instead.
enum EmbeddedBenchmarks {
    static let cisMacOS: String = #"""
'''

FOOTER = '"""#\n}\n'


def render() -> str:
    yaml_text = YAML.read_text()
    if '"""#' in yaml_text:
        sys.exit(f"error: {YAML} contains '\"\"\"#', which would terminate the Swift raw string literal")
    return HEADER + yaml_text + FOOTER


def main() -> int:
    generated = render()
    check = "--check" in sys.argv[1:]

    if check:
        current = SWIFT.read_text() if SWIFT.exists() else ""
        if current != generated:
            print(f"error: {SWIFT.relative_to(ROOT)} is out of date.", file=sys.stderr)
            print("Run: python3 Scripts/embed_benchmarks.py", file=sys.stderr)
            return 1
        print(f"{SWIFT.relative_to(ROOT)} is in sync with {YAML.name}")
        return 0

    SWIFT.write_text(generated)
    print(f"Wrote {SWIFT.relative_to(ROOT)} from {YAML.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
